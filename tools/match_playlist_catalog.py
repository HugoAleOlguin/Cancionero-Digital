def norm(s):
    import unicodedata
    return ''.join(c for c in unicodedata.normalize('NFD', s.lower()) if unicodedata.category(c) != 'Mn')

print("=== Cotejando canciones de la lista contra catálogo ===")
for vid, title in playlist_items:
    nt = norm(title)
    for h in cat:
        nh = norm(h['title'])
        if nt == nh or nt in nh or nh in nt:
            has_link = bool(h.get('link', '').strip())
            print(f"Match: [{vid}] '{title}'  <-->  #{h['id']} '{h['title']}' ({h.get('author')}) | Has link: {has_link}")
